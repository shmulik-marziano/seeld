  fund_name                 text not null,
  fund_classification       text,
  managing_company          text,
  managing_company_id       text,
  source                    text not null,
  product_type              text,
  specialization            text,
  sub_specialization        text,
  target_population         text,
  report_period             integer not null,
  inception_date            text,
  total_assets              numeric,
  deposits                  numeric,
  withdrawals               numeric,
  internal_transfers        numeric,
  net_monthly_deposits      numeric,
  monthly_yield             numeric,
  ytd_yield                 numeric,
  yield_trailing_3yrs       numeric,
  yield_trailing_5yrs       numeric,
  avg_annual_yield_3yrs     numeric,
  avg_annual_yield_5yrs     numeric,
  avg_annual_management_fee numeric,
  avg_deposit_fee           numeric,
  standard_deviation        numeric,
  alpha                     numeric,
  sharpe_ratio              numeric,
  liquid_assets_percent     numeric,
