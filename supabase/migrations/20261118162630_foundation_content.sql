create index cma_funds_fund_name_trgm_idx on content.cma_funds using gin (fund_name extensions.gin_trgm_ops);

-- sync log. Fix of the Tokyo defect: 'stale' is an allowed status (the freshness check writes it).
create table content.cma_sync_log (
  id               uuid primary key default gen_random_uuid(),
  source           text not null,
  status           text not null check (status in ('success', 'error', 'partial', 'stale')),
  records_fetched  integer,
  records_upserted integer,
  latest_period    integer,
  error_message    text,
  duration_ms      integer,
  started_at       timestamptz not null default now(),
  completed_at     timestamptz
);
create index cma_sync_log_source_started_idx on content.cma_sync_log (source, started_at desc);

-- triggers -----------------------------------------------------------------------
create trigger blog_posts_set_updated_at before update on content.blog_posts
  for each row execute function private.set_updated_at();
create trigger travel_companies_set_updated_at before update on content.travel_companies
  for each row execute function private.set_updated_at();
create trigger investment_tracks_set_updated_at before update on content.investment_tracks
  for each row execute function private.set_updated_at();
create trigger blog_posts_audit after insert or update or delete on content.blog_posts
  for each row execute function audit.log_change();
create trigger travel_companies_audit after insert or update or delete on content.travel_companies
  for each row execute function audit.log_change();

-- RLS ------------------------------------------------------------------------------
alter table content.blog_posts        enable row level security;
alter table content.travel_companies  enable row level security;
alter table content.investment_tracks enable row level security;
alter table content.cma_funds         enable row level security;
alter table content.cma_sync_log      enable row level security;

-- grants: least privilege, never TRUNCATE/REFERENCES/TRIGGER for API roles
grant select on content.blog_posts, content.travel_companies, content.investment_tracks, content.cma_sync_log to anon;
grant select on content.blog_posts, content.travel_companies, content.investment_tracks, content.cma_sync_log, content.cma_funds to authenticated;
grant insert, update on content.blog_posts, content.travel_companies to authenticated;
grant delete on content.blog_posts, content.travel_companies to authenticated;  -- policy limits to managers
grant select, insert, update, delete on all tables in schema content to service_role;

-- blog_posts
create policy blog_select_anon on content.blog_posts for select to anon
  using (status = 'published' and published_at <= now());
create policy blog_select_staff on content.blog_posts for select to authenticated
  using ((status = 'published' and published_at <= now()) or (select private.is_staff()));
create policy blog_insert on content.blog_posts for insert to authenticated
  with check ((select private.is_staff()));
create policy blog_update on content.blog_posts for update to authenticated
  using ((select private.is_staff())) with check ((select private.is_staff()));
create policy blog_delete on content.blog_posts for delete to authenticated
  using ((select private.is_manager()));

-- travel_companies
create policy travel_select_anon on content.travel_companies for select to anon using (active);
create policy travel_select_staff on content.travel_companies for select to authenticated
  using (active or (select private.is_staff()));
create policy travel_insert on content.travel_companies for insert to authenticated
  with check ((select private.is_staff()));
create policy travel_update on content.travel_companies for update to authenticated
  using ((select private.is_staff())) with check ((select private.is_staff()));
create policy travel_delete on content.travel_companies for delete to authenticated
  using ((select private.is_manager()));

-- investment_tracks: public read of active rows; writes only by service_role (loader)
create policy tracks_select_anon on content.investment_tracks for select to anon using (is_active);
create policy tracks_select_auth on content.investment_tracks for select to authenticated
  using (is_active or (select private.is_staff()));

-- cma_funds: base table is NOT public (39k rows). Public gets derived views. Staff may read.
create policy cma_funds_select_staff on content.cma_funds for select to authenticated
  using ((select private.is_staff()));

-- sync log: public read (site shows data freshness)
create policy sync_log_select_anon on content.cma_sync_log for select to anon using (true);
create policy sync_log_select_auth on content.cma_sync_log for select to authenticated using (true);
