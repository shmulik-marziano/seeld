-- FOUNDATION 04: site-public content (blog, travel, investment tracks, fund returns).
-- Anon reads published/active rows only, and only through api views (migration 06).
-- Writes: staff (aal2) from the agent app, service_role from loaders (fetch-cma-data, sync-tracks).
-- One SELECT policy per role: avoids the "multiple permissive policies" performance lint.

-- blog ----------------------------------------------------------------------
create table content.blog_posts (
  id              uuid primary key default gen_random_uuid(),
  slug            text not null unique check (slug ~ '^[^\s/]+$' and char_length(slug) <= 200),
  title           text not null check (char_length(title) between 1 and 300),
  excerpt         text,
  content         text not null,
  category        text,
  cover_image_url text,
  author          text,
  status          text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  published_at    timestamptz,
  created_by      uuid references auth.users (id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  check (status <> 'published' or published_at is not null)
);
create index blog_posts_published_idx on content.blog_posts (published_at desc) where status = 'published';
create index blog_posts_created_by_idx on content.blog_posts (created_by);

-- travel companies ---------------------------------------------------------------
create table content.travel_companies (
  id          uuid primary key default gen_random_uuid(),
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name        text not null check (char_length(name) between 1 and 120),
  description text,
  website_url text check (website_url is null or website_url ~ '^https://'),
  phone       text,
  logo_url    text,
  coverage    jsonb not null default '{}'::jsonb,
  sort_order  integer not null default 100,
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index travel_companies_active_idx on content.travel_companies (sort_order) where active;

-- investment tracks (loaded by sync-tracks) ----------------------------------------
create table content.investment_tracks (
  id              bigint generated by default as identity primary key,
  fund_number     text not null unique,
  name            text not null,
  company         text not null,
  product_type    text not null,
  specialization  text not null,
  stock_exposure  integer,
  return_year1    numeric(8,2),
  return_year3    numeric(8,2),
  return_year5    numeric(8,2),
  return_month    numeric(8,2),
  fee_assets      numeric(6,3),
  fee_deposits    numeric(6,3),
  sharpe_ratio    numeric(6,3),
  total_assets    numeric(12,2),
  liquidity       numeric(6,2),
  report_period   text,
  foreign_exposure numeric(6,2),
  currency_exposure numeric(6,2),
  stocks_pct      numeric(6,2),
  gov_bonds_pct   numeric(6,2),
  corp_bonds_pct  numeric(6,2),
  cash_pct        numeric(6,2),
  other_pct       numeric(6,2),
  is_active       boolean not null default true,
  last_sync       timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index investment_tracks_active_company_idx on content.investment_tracks (company) where is_active;

-- fund returns (data.gov.il, loaded by fetch-cma-data). raw_data is NOT carried over (kept in the archive). -------
