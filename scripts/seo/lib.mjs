/** llms.txt: compact route map, one line per page, in the llmstxt.org layout. */
export function buildLlms(d, posts = []) {
  const L = [];
  L.push("# שילד (SEELD) | סוכנות ביטוח ופיננסים", "");
  L.push("> שילד היא סוכנות ביטוח ופיננסים הפועלת בישראל. השירות: מיפוי תיק הביטוח, הפנסיה והחיסכון של הלקוח, השוואה בין חברות הביטוח וגופי ההשקעה, וליווי הביצוע. פגישת ייעוץ ראשונה. גרסה מורחבת עם תקצירי תשובה לכל עמוד: " + url(d, "/llms-full.txt"), "");
  L.push("## עובדות על העסק", "", ...FACTS(d), "");
  L.push("## איך לצטט", "", ...CITE(d), "");
  for (const [g, title] of GROUPS) {
    const rows = d.ROUTES.filter((e) => e.group === g);
    if (!rows.length) continue;
    L.push(`## ${title}`, "");
    for (const e of rows) L.push(`- [${d.labelFromTitle(e.title)}](${url(d, e.path)}): ${oneLine(e.description)}`);
    L.push("");
  }
  if (posts.length) {
    L.push("## מאמרים בבלוג", "");
    for (const p of posts) L.push(`- [${oneLine(p.title)}](${url(d, `/blog/${p.slug}`)})${p.excerpt ? `: ${oneLine(p.excerpt)}` : ""}`);
    L.push("");
  }
  L.push("## הערת שימוש", "", NOTE, "");
  return L.join("\n");
}

/** llms-full.txt: everything an answer engine needs in one file (summary, description, links, FAQ). */
export function buildLlmsFull(d, posts = []) {
  const L = [];
  L.push("# שילד (SEELD) | סוכנות ביטוח ופיננסים: מידע מלא לכלי בינה", "");
  L.push("> קובץ זה מרכז את כל העמודים הציבוריים באתר, עם תקציר תשובה קצר לכל עמוד, תיאור וקישורים קשורים. הוא נוצר אוטומטית ממאגר העמודים של האתר.", "");
  L.push("## עובדות על העסק", "", ...FACTS(d), "");
  L.push("## איך לצטט", "", ...CITE(d), "");
  for (const [g, title] of GROUPS) {
    const rows = d.ROUTES.filter((e) => e.group === g);
    if (!rows.length) continue;
    L.push(`## ${title}`, "");
    for (const e of rows) {
      L.push(`### ${d.labelFromTitle(e.title)}`, "");
      L.push(`- כתובת: ${url(d, e.path)}`);
      L.push(`- תיאור: ${oneLine(e.description)}`);
      L.push(`- תקציר: ${oneLine(d.summaries[e.path])}`);
      const rel = (e.related ?? []).map((p) => d.ROUTE_BY_PATH[p]).filter(Boolean);
      if (rel.length) L.push(`- עמודים קשורים: ${rel.map((x) => `[${d.labelFromTitle(x.title)}](${url(d, x.path)})`).join(", ")}`);
      L.push("");
    }
  }
  L.push("## שאלות ותשובות נפוצות", "", `מקור: ${url(d, "/faq")}`, "");
  for (const c of d.faqCategories) {
    L.push(`### ${c.title}`, "");
    for (const q of c.questions) L.push(`**${oneLine(q.q)}**`, oneLine(q.a), "");
  }
  if (posts.length) {
    L.push("## מאמרים בבלוג", "");
    for (const p of posts) {
      L.push(`### ${oneLine(p.title)}`, "", `- כתובת: ${url(d, `/blog/${p.slug}`)}`);
      if (p.excerpt) L.push(`- תקציר: ${oneLine(p.excerpt)}`);
      L.push("");
    }
  }
  L.push("## הערת שימוש", "", NOTE, "");
  return L.join("\n");
}
