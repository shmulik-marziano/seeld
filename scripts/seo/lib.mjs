// Shared SEO/AEO build helpers: load the TypeScript data modules from Node and generate
// sitemap.xml, llms.txt and llms-full.txt from the single route registry.
// Used by scripts/prerender.mjs (build), scripts/seo-generate.mjs and scripts/check-aeo.mjs.
import { build } from "esbuild";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

/** Bundles a TS module with esbuild (ships with vite) and imports it: no dependency on Node's TS support. */
async function loadTs(relPath) {
  const out = await build({
    entryPoints: [join(ROOT, relPath)], bundle: true, format: "esm", platform: "node", write: false, logLevel: "silent",
  });
  const dir = await mkdtemp(join(tmpdir(), "seeld-seo-"));
  try {
    const file = join(dir, "m.mjs");
    await writeFile(file, out.outputFiles[0].text);
    return await import(pathToFileURL(file).href);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

export async function loadData() {
  const [routes, summaries, faq] = await Promise.all([
    loadTs("src/data/seo/routes.ts"),
    loadTs("src/data/answerSummaries.ts"),
    loadTs("src/data/faq.ts"),
  ]);
  return {
    SITE_URL: routes.SITE_URL, CONTENT_REVIEWED: routes.CONTENT_REVIEWED,
    ROUTES: routes.ROUTES, ROUTE_BY_PATH: routes.ROUTE_BY_PATH, labelFromTitle: routes.labelFromTitle,
    summaries: summaries.answerSummaries, faqCategories: faq.faqCategories,
  };
}

const xmlEscape = (v) => String(v).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const oneLine = (v) => String(v ?? "").replace(/\s+/g, " ").trim();
const url = (d, p) => `${d.SITE_URL}${p === "/" ? "/" : p}`;

/** sitemap.xml: lastmod, changefreq, priority and hreflang (he-IL + x-default) for every URL. */
export function buildSitemap(d, posts = []) {
  const alt = (loc) =>
    `<xhtml:link rel="alternate" hreflang="he-IL" href="${loc}"/><xhtml:link rel="alternate" hreflang="x-default" href="${loc}"/>`;
  const entries = d.ROUTES.map((e) => ({
    loc: url(d, e.path), lastmod: d.CONTENT_REVIEWED, changefreq: e.changefreq, priority: e.priority.toFixed(1),
  }));
  for (const p of posts) {
    entries.push({
      loc: url(d, `/blog/${p.slug}`),
      lastmod: (p.updated_at ?? p.published_at ?? d.CONTENT_REVIEWED).slice(0, 10),
      changefreq: "monthly", priority: "0.6",
    });
  }
  const urls = entries.map((e) =>
    `  <url><loc>${xmlEscape(e.loc)}</loc><lastmod>${e.lastmod}</lastmod><changefreq>${e.changefreq}</changefreq><priority>${e.priority}</priority>${alt(xmlEscape(e.loc))}</url>`);
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!-- Generated by scripts/seo-generate.mjs and scripts/prerender.mjs from src/data/seo/routes.ts. Do not edit by hand. -->",
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...urls, "</urlset>", "",
  ].join("\n");
}

